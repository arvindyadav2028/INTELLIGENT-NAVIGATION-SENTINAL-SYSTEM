    private void b1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b1ActionPerformed
        //GEN-FIRST:event_b1ActionPerformed

        UserSession.getInstance().resetInactivityTimer();

        String input = tf1.getText().trim();
        if (input.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a value or scan a QR code.",
                "Input Required", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (chkb1.isSelected()) {
            // ── VEHICLE CHECK ──────────────────────────────────────
            // Strip INSS QR payload if user scanned a QR
            // QR format: INSS|VEH|{VRegNo}|{OwnerName}|{SerialNo}
            String vehicleNo = input;
            if (input.startsWith("INSS|VEH|")) {
                String[] parts = input.split("\\|");
                vehicleNo = parts.length > 2 ? parts[2] : input;
            }

            // Open PbtVhReg in check mode — vhCheck() loads all details
            PbtVhReg dialog = new PbtVhReg(new javax.swing.JFrame(), true, vehicleNo);
            dialog.setLocationRelativeTo(null);
            dialog.setVisible(true);

            // Log this check attempt
            logCheckAttempt(vehicleNo, "VEHICLE", "CHECKED");

        } else if (chkb2.isSelected()) {
            // ── PERSON CHECK ───────────────────────────────────────
            // Strip INSS QR payload if scanned
            // QR format: INSS|PERSON|{GroupCode}|{LeaderName}|{Count}
            String identifier = input;
            if (input.startsWith("INSS|PERSON|")) {
                String[] parts = input.split("\\|");
                identifier = parts.length > 2 ? parts[2] : input; // GroupCode
            }

            lookupPerson(identifier);

        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Please select 'Vehicle' or 'Person' before submitting.",
                "Select Check Type", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
        //GEN-LAST:event_b1ActionPerformed
    }//GEN-LAST:event_b1ActionPerformed

