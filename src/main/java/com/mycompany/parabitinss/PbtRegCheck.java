    /**
     * Opens the QR scanner with a callback.
     * When a code is scanned, fills tf1 and automatically triggers b1.
     */
    private void launchQrScanner() {
        UserSession.getInstance().resetInactivityTimer();
        // QrScanner callback constructor — defined in Sprint 1
        new QrScanner(decodedText -> {
            tf1.setText(decodedText);
            // Auto-trigger lookup after half-second (lets UI update first)
            javax.swing.Timer delay = new javax.swing.Timer(500, e -> b1ActionPerformed(null));
            delay.setRepeats(false);
            delay.start();
        });
    }

    /**
     * Looks up a person in personreg by Aadhaar number OR GroupCode.
     * Shows a summary dialog with person/group details.
     */
    private void lookupPerson(String identifier) {
        try {
            ParabitDBC db = new ParabitDBC();

            // Try Aadhaar lookup first (12 digits), then GroupCode
            boolean isAadhaar = identifier.replaceAll("\\D", "").length() == 12;

            String sql;
            if (isAadhaar) {
                sql = "SELECT PersonName, MobileNo, AadharNo, Gender, Age, " +
                      "TownCity, State, GroupCode, IsGroupLeader, RegDate " +
                      "FROM personreg WHERE AadharNo = ?";
            } else {
                // Group code — show all members of the group
                sql = "SELECT PersonName, MobileNo, AadharNo, Gender, Age, " +
                      "TownCity, State, GroupCode, IsGroupLeader, RegDate " +
                      "FROM personreg WHERE GroupCode = ? ORDER BY IsGroupLeader DESC";
            }

            db.ps = db.con.prepareStatement(sql);
            db.ps.setString(1, identifier);
            db.rs = db.ps.executeQuery();

            if (!db.rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "No registration found for: " + identifier + "\n\n"
                    + "This person/group is NOT registered for the event.",
                    "Not Found ❌",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                logCheckAttempt(identifier, "PERSON", "NOT_FOUND");
                return;
            }

            // Build result display
            StringBuilder sb = new StringBuilder();
            sb.append("✅  REGISTERED\n");
            sb.append("─────────────────────────────\n");
            int count = 0;
            do {
                count++;
                boolean isLeader = db.rs.getInt("IsGroupLeader") == 1;
                sb.append(isLeader ? "👤 LEADER  " : "👥 Member  ");
                sb.append(db.rs.getString("PersonName")).append("\n");
                sb.append("   Aadhaar : ").append(db.rs.getString("AadharNo")).append("\n");
                sb.append("   Mobile  : ").append(db.rs.getString("MobileNo")).append("\n");
                sb.append("   Gender  : ").append(db.rs.getString("Gender"))
                  .append("  |  Age: ").append(db.rs.getString("Age")).append("\n");
                sb.append("   Location: ").append(db.rs.getString("TownCity"))
                  .append(", ").append(db.rs.getString("State")).append("\n");
                sb.append("   Group   : ").append(db.rs.getString("GroupCode")).append("\n");
                sb.append("   Reg Date: ").append(db.rs.getString("RegDate")).append("\n");
                if (count < 10) sb.append("\n"); // separator between members
            } while (db.rs.next() && count < 10); // cap at 10 rows in dialog

            if (count == 10) sb.append("... and more members in this group.\n");

            javax.swing.JOptionPane.showMessageDialog(this,
                sb.toString(), "Person Found ✅",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);

            logCheckAttempt(identifier, "PERSON", "FOUND");

        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Database error during lookup: " + ex.getMessage(),
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    /**
     * Logs every check attempt to personlog table for audit trail.
     * Silently does nothing if the log table doesn't exist yet.
     */
    private void logCheckAttempt(String identifier, String checkType, String result) {
        try {
            ParabitDBC db = new ParabitDBC();
            db.ps = db.con.prepareStatement(
                "INSERT INTO personlog(Identifier, CheckType, CheckResult, " +
                "CheckedBy, CheckTime) VALUES(?, ?, ?, ?, NOW())");
            db.ps.setString(1, identifier);
            db.ps.setString(2, checkType);
            db.ps.setString(3, result);
            db.ps.setString(4, UserSession.getInstance().getEmpId());
            db.ps.executeUpdate();
        } catch (Exception ex) {
            // Log table may not exist yet — non-critical, don't crash
            System.err.println("[PbtRegCheck] logCheckAttempt skipped: " + ex.getMessage());
        }
    }

